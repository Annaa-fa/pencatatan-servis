-- 1. PEMBUATAN TABEL SERVICES DENGAN VALIDASI CONSTRAINT LEVEL DATABASE
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_servis VARCHAR(30) NOT NULL,
    nama_pelanggan VARCHAR(100) NOT NULL,
    nama_barang VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Diterima',
    biaya_akhir DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    
    -- Constraint Unik untuk Nomor Servis
    CONSTRAINT services_no_servis_unique UNIQUE (no_servis),
    
    -- Constraint Validasi Nilai Status (Sesuai ENUM Modul 2 SKPL)
    CONSTRAINT check_status_valid CHECK (
        status IN ('Diterima', 'Diperiksa', 'Diproses', 'Selesai', 'Diambil')
    ),
    
    -- Constraint Validasi Biaya Akhir (TC-01 & TC-02: Tidak boleh negatif)
    CONSTRAINT check_biaya_akhir_non_negative CHECK (
        biaya_akhir >= 0.00
    ),
    
    -- Constraint Integritas String (Mencegah input string kosong/spasi saja)
    CONSTRAINT check_no_servis_not_empty CHECK (
        length(trim(no_servis)) > 0
    ),
    CONSTRAINT check_nama_pelanggan_not_empty CHECK (
        length(trim(nama_pelanggan)) > 0
    ),
    CONSTRAINT check_nama_barang_not_empty CHECK (
        length(trim(nama_barang)) > 0
    )
);

-- Memberikan komentar pada tabel dan kolom untuk dokumentasi schema
COMMENT ON TABLE public.services IS 'Tabel utama pencatatan transaksi dan tracking servis ServiceTrack';
COMMENT ON COLUMN public.services.id IS 'Primary key unik transaksi servis';
COMMENT ON COLUMN public.services.no_servis IS 'Nomor identitas unik tanda terima servis';
COMMENT ON COLUMN public.services.nama_pelanggan IS 'Nama lengkap pelanggan pemilik barang';
COMMENT ON COLUMN public.services.nama_barang IS 'Nama dan tipe barang elektronik yang diservis';
COMMENT ON COLUMN public.services.status IS 'Tahapan pengerjaan servis (Diterima, Diperiksa, Diproses, Selesai, Diambil)';
COMMENT ON COLUMN public.services.biaya_akhir IS 'Total nominal biaya akhir servis (minimal 0)';

-- 2. MENGAKTIFKAN FITUR ROW LEVEL SECURITY (RLS)
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;

-- 3. KEBIJAKAN AKSES (POLICIES) UNTUK ROLE ANON (PUBLIC CLIENT WORKSHOP DEMO)
-- Menghapus policy lama jika ada untuk mencegah konflik eksekusi ulang
DROP POLICY IF EXISTS "Allow anon select all services" ON public.services;
DROP POLICY IF EXISTS "Allow anon insert services with validation" ON public.services;
DROP POLICY IF EXISTS "Allow anon update services with validation" ON public.services;
DROP POLICY IF EXISTS "Allow anon delete services" ON public.services;

-- A. Policy SELECT (Membaca seluruh data servis untuk tabel dan KPI)
CREATE POLICY "Allow anon select all services" 
ON public.services 
FOR SELECT 
TO anon 
USING (true);

-- B. Policy INSERT (Menambah transaksi baru dengan verifikasi batasan constraint)
CREATE POLICY "Allow anon insert services with validation" 
ON public.services 
FOR INSERT 
TO anon 
WITH CHECK (
    length(trim(no_servis)) > 0 
    AND length(trim(nama_pelanggan)) > 0 
    AND length(trim(nama_barang)) > 0 
    AND status IN ('Diterima', 'Diperiksa', 'Diproses', 'Selesai', 'Diambil')
    AND biaya_akhir >= 0.00
);

-- C. Policy UPDATE (Memperbarui status pengerjaan atau biaya akhir dengan verifikasi)
CREATE POLICY "Allow anon update services with validation" 
ON public.services 
FOR UPDATE 
TO anon 
USING (true)
WITH CHECK (
    length(trim(no_servis)) > 0 
    AND length(trim(nama_pelanggan)) > 0 
    AND length(trim(nama_barang)) > 0 
    AND status IN ('Diterima', 'Diperiksa', 'Diproses', 'Selesai', 'Diambil')
    AND biaya_akhir >= 0.00
);

-- D. Policy DELETE (Menghapus baris transaksi servis)
CREATE POLICY "Allow anon delete services" 
ON public.services 
FOR DELETE 
TO anon 
USING (true);

